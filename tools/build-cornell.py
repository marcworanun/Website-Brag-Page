#!/usr/bin/env python3
"""Builds cornell.html, the Cornell (hotel administration) version of the brag page.

cornell.html is index.html with two changes:
  - the Internship block, from "<!-- INTERNSHIP" to "<!-- /INTERNSHIP -->", is replaced by
    cornell/work-experience.html
  - the Internship tab becomes Work Experience
Everything else is shared, so a change to projects, awards or photos goes in index.html and
reaches both pages when this runs. Edit index.html or cornell/work-experience.html, never
cornell.html itself. tools/build-netlify.sh runs this automatically.

Usage: tools/build-cornell.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
page = (root / "index.html").read_text(encoding="utf-8")
work = (root / "cornell" / "work-experience.html").read_text(encoding="utf-8").rstrip("\n") + "\n"

block = re.compile(r"^[ \t]*<!-- INTERNSHIP\b.*?^[ \t]*<!-- /INTERNSHIP -->\n", re.M | re.S)
if len(block.findall(page)) != 1:
    raise SystemExit("index.html needs exactly one <!-- INTERNSHIP ... --> ... <!-- /INTERNSHIP --> block")
page = block.sub(lambda _: work, page)

tab = '<a href="#internship">Internship</a>'
if page.count(tab) != 1:
    raise SystemExit(f"index.html needs exactly one {tab} tab")
page = page.replace(tab, '<a href="#work-experience"><span class="long">Work </span>Experience</a>')

doctype = "<!doctype html>\n"
if not page.lower().startswith(doctype):
    raise SystemExit("index.html should start with <!doctype html>")
note = ("<!-- Generated by tools/build-cornell.py from index.html and cornell/work-experience.html.\n"
        "     Edit those files and rerun it; changes made here are overwritten. -->\n")
page = page[:len(doctype)] + note + page[len(doctype):]

(root / "cornell.html").write_text(page, encoding="utf-8")
print("Built cornell.html")
